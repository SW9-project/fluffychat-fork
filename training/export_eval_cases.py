"""Exports the held-out examples for the on-device evaluation.

    python3 training/export_eval_cases.py

Reads Train2/data/eval.jsonl and Train2/data/eval_rendered.jsonl and writes
integration_test/personalization_eval_cases.dart: per example its id, kind,
the conversation before the final call, the expected call, and the prompt the
training render produced, so the phone can check that LiteRT-LM renders the
same text. integration_test/personalization_model_test.dart runs them.
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "integration_test" / "personalization_eval_cases.dart"


def main() -> None:
    rendered = {
        r["id"]: r for r in map(json.loads, (HERE / "Train2/data/eval_rendered.jsonl").open())
    }
    # The declarations are the same in every prompt: kept once.
    marker = "<end_function_declaration><end_of_turn>\n"
    prompts = [r["prompt"] for r in rendered.values()]
    prefix = prompts[0][: prompts[0].index(marker) + len(marker)]
    if not all(p.startswith(prefix) for p in prompts):
        raise SystemExit("The prompts do not share their declarations")
    cases = []
    for example in map(json.loads, (HERE / "Train2/data/eval.jsonl").open()):
        *before, last = example["messages"]
        call = last["tool_calls"][0]["function"]
        cases.append(
            {
                "id": example["id"],
                "kind": example["kind"],
                "messages": before,
                "expected": {"name": call["name"], "arguments": call["arguments"]},
                "prompt_after_declarations": rendered[example["id"]]["prompt"][
                    len(prefix) :
                ],
            }
        )
    body = json.dumps(cases, ensure_ascii=False, indent=1)
    if "'''" in body or "'''" in prefix:
        raise SystemExit("A case contains ''' and cannot go in a raw string")
    OUT.write_text(
        "// SPDX-FileCopyrightText: 2026 SW9-project contributors\n"
        "//\n"
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n\n"
        "// Generated by training/export_eval_cases.py from training/data. Do not\n"
        "// edit.\n"
        f"const declarationsPrompt = r'''{prefix}''';\n\n"
        f"const evalCasesJson = r'''\n{body}\n''';\n"
    )
    print(f"Wrote {len(cases)} cases to {OUT}")


if __name__ == "__main__":
    main()
