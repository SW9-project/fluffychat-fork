import 'dart:convert';
import 'dart:io';

import 'package:fluffychat/personalization/accessibility_settings.dart';
import 'package:fluffychat/personalization/assist/assist_prompt.dart';
import 'package:fluffychat/personalization/settings_registry.dart';
import 'package:flutter_test/flutter_test.dart';

/// The evaluation script (`llm-proxy/eval/`) sends the app's real system
/// prompt and tools. This test keeps its fixture equal to what the app
/// builds, so the evaluation can never drift from the app.
///
/// After changing the registry or `assets/assist/heuristics.md`, refresh it:
///
///     UPDATE_ASSIST_FIXTURE=1 flutter test test/personalization/assist_eval_fixture_test.dart
const fixturePath = 'llm-proxy/eval/fixtures/assist_request.json';
const settingsHeader = 'Current settings (1.0 is normal):';

String buildFixture() {
  final template = AssistPromptTemplate.parse(
    File(AssistPromptTemplate.assetPath).readAsStringSync(),
  );
  final prompt = AssistPromptBuilder.build(
    template,
    AccessibilitySettings.defaults,
  );
  final system = prompt.system;
  final prefix = system.substring(
    0,
    system.indexOf('\n$settingsHeader\n') + settingsHeader.length + 1,
  );
  final fixture = {
    r'$comment':
        'Generated by test/personalization/assist_eval_fixture_test.dart. '
        'Do not edit.',
    'settingsHeader': settingsHeader,
    'systemPrefix': prefix,
    'systemWithDefaults': system,
    'settings': [
      for (final s in SettingsRegistry.all.cast<NumberSetting>())
        {
          'id': s.id,
          'min': s.min,
          'max': s.max,
          'step': s.step,
          'default': s.defaultValue,
        },
    ],
    'tools': [for (final t in prompt.tools) t.toJson()],
  };
  return '${const JsonEncoder.withIndent('  ').convert(fixture)}\n';
}

void main() {
  test('the evaluation fixture matches the app', () {
    final expected = buildFixture();
    final file = File(fixturePath);
    if (Platform.environment['UPDATE_ASSIST_FIXTURE'] == '1') {
      file
        ..createSync(recursive: true)
        ..writeAsStringSync(expected);
    }
    expect(
      file.existsSync() ? file.readAsStringSync().replaceAll('\r\n', '\n') : '',
      expected,
      reason:
          'Run UPDATE_ASSIST_FIXTURE=1 flutter test '
          'test/personalization/assist_eval_fixture_test.dart',
    );
  });
}
